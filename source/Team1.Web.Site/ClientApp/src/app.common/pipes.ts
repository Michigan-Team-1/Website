@Pipe({
    name: "spudYesNo"
})
export class YesNoPipe implements PipeTransform {
    constructor() { }

    transform(value: any, withColor: boolean): string {
        let cssClass = "";
        if (value) {
            cssClass+= "far fa-check-square ";
            if (withColor) cssClass += "text-success";
        }
        else {
            cssClass+= "far fa-square "
            if (withColor) cssClass += "text-warning";
        }
        return `<i class="${cssClass}"></i>`;
    }
}

