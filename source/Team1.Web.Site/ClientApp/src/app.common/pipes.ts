@Pipe({
  name: "stringLengthErrorMessage"
})
export class StringLengthErrorMessage implements PipeTransform {
  constructor() { }

  /**
   * Value must be the attribute object generated by typewriter
   */
  transform(value: any): string {
    if (value == null) return "";
    let msg = value.stringLength.errorMessage.replace("{0}", value.name);
    if (value.stringLength.maxLength) {
      msg = msg.replace("{1}", value.stringLength.maxLength.toString());
    }
    if (value.stringLength.minimumLength) {
      msg = msg.replace("{2}", value.stringLength.minimumLength.toString());
    }
    return msg;
  }
}

